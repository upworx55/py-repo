
# List Slicing: - It is similar to String slicing

marks = [85, 94, 76, 63, 48]
print(marks[1:4]) # 4th (last index mentioned here) element not included.
print(marks[0:3]) # 3rd (last index mentioned here) element not included.
print(marks[:4]) # value prints from 0th - 3rd element.
print(marks[1:]) # value prints from 1st - 4th element.
print(marks[-3:-1]) # value prints from -3rd to -2nd element.
