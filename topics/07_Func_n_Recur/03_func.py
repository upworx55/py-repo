
# Function Types: There are two types of functions in Python: built-in functions and user-defined functions.
# Built-in functions: are functions that are already defined in Python and can be used without any additional code.
# Examples: print(), len(), abs(), max(), min(), sum(), etc.
print(len("Hello"))  # prints the length of the string
print(abs(-5))  # prints the absolute value of the number
print(max(1, 2, 3))  # prints the maximum value
print(min(1, 2, 3))  # prints the minimum value
print(sum([1, 2, 3]))  # prints the sum of the list

# User-defined functions: are functions that are defined by the user to perform specific tasks. They can take parameters and return values.
def greet(name):
    return f"Hello, {name}!"

print(greet("Alice"))  # calling the user-defined function and printing the result




